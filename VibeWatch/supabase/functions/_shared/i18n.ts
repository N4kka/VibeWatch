// Push and email copy, in the reader's language.
//
// Until now every producer wrote a finished English sentence into `notifications.title/body` at
// enqueue time — hours before delivery, without knowing who would read it. The queue now carries
// a `template_key` plus the parts that vary (`template_params`), and the text is assembled here,
// at send time, from the recipient's `user_notification_preferences.language`.
//
// The catalog mirrors the app's 20 locales. `en` is complete by definition and is the fallback
// for a missing locale *and* for a missing key inside a locale, so a half-translated language
// degrades one string at a time instead of failing. Placeholders are `{name}`; an absent
// parameter renders as an empty string, which is why the `_about` variants exist as separate
// keys rather than being built by concatenation.

export const FALLBACK_LANGUAGE = 'en'

