/** Normalizes 'it-IT', 'pt_BR', 'IT' to a catalog key, falling back to English. */
export function normalizeLanguage(language?: string | null): string {
  if (!language) return FALLBACK_LANGUAGE
  const base = language.toLowerCase().replace('_', '-').split('-')[0]
  return CATALOGS[base] ? base : FALLBACK_LANGUAGE
}

function interpolate(template: string, params: TemplateParams): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const value = params[key]
    return value === null || value === undefined ? '' : String(value)
  })
}

/** One string, in the reader's language. Falls back to English, then to the key itself. */
export function t(language: string | null | undefined, key: string, params: TemplateParams = {}): string {
  const catalog = CATALOGS[normalizeLanguage(language)]
  const template = catalog[key] ?? en[key]
  if (!template) return key
  return interpolate(template, params)
}

export type RenderedNotification = { title: string; body: string }

// Which pair of catalog keys a queued row resolves to, and when a variant applies. Producers
// write the key and the parameters; the choice between "with an episode label" and "without" or
// "one provider" and "several" lives here, next to the strings it selects between.
export function renderNotification(
  templateKey: string | null | undefined,
  params: TemplateParams | null | undefined,
  language: string | null | undefined
): RenderedNotification | null {
  if (!templateKey) return null
  const p: TemplateParams = { ...(params ?? {}) }

  // An anonymous actor is a localized word, not the literal 'Someone' the trigger wrote.
  if ('name' in p && !p.name) p.name = t(language, 'someone')

  switch (templateKey) {
    case 'new_availability': {
      const kindKey = `kind.${String(p.kind ?? 'stream')}`
      const kind = t(language, kindKey)
      const more = Number(p.count ?? 0)
      return {
        title: t(language, 'push.new_availability.title', p),
        body: more > 0
          ? t(language, 'push.new_availability.body_more', { ...p, kind, count: more })
          : t(language, 'push.new_availability.body', { ...p, kind }),
      }
    }
    case 'new_release':
      return {
        title: t(language, 'push.new_release.title'),
        body: t(language, 'push.new_release.body', p),
      }
    case 'episode_aired':
      return {
        title: t(language, 'push.episode_aired.title'),
        body: p.episode
          ? t(language, 'push.episode_aired.body', p)
          : t(language, 'push.episode_aired.body_generic', p),
      }
    case 'continue_watching':
      return {
        title: t(language, 'push.continue_watching.title'),
        body: t(language, 'push.continue_watching.body', p),
      }
    case 'streak_reminder':
      return {
        title: t(language, 'push.streak_reminder.title'),
        body: t(language, 'push.streak_reminder.body', p),
      }
    case 'import_done':
      return {
        title: t(language, 'push.import_done.title'),
        body: Number(p.pending ?? 0) > 0
          ? t(language, 'push.import_done.body_review', p)
          : t(language, 'push.import_done.body', p),
      }
    case 'new_follower':
      return {
        title: t(language, 'push.new_follower.title'),
        body: t(language, 'push.new_follower.body', p),
      }
    case 'activity_liked':
    case 'activity_liked_about':
      return {
        title: t(language, 'push.activity_liked.title'),
        body: templateKey === 'activity_liked_about' && p.title
          ? t(language, 'push.activity_liked_about.body', p)
          : t(language, 'push.activity_liked.body', p),
      }
    case 'activity_commented':
    case 'activity_commented_about':
      return {
        title: t(language, 'push.activity_commented.title'),
        body: templateKey === 'activity_commented_about' && p.title
          ? t(language, 'push.activity_commented_about.body', p)
          : t(language, 'push.activity_commented.body', p),
      }
    default:
      // An unknown key means a producer newer than this module: the caller keeps the stored
      // English copy rather than showing a raw key.
      return null
  }
}

